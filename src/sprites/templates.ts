/**
 * The hand-authored shapes. Each is a 16 by 16 grid drawn with roles rather
 * than colours, so one drawing can be recoloured for any cart:
 *
 *   .  nothing        a  main fill      b  shade
 *   c  highlight      e  eye white      p  pupil or dark detail
 *   m  mouth          X  hard outline
 *
 * Outlines are added automatically around anything that is not explicitly
 * outlined, which is what keeps the silhouettes strong.
 */

export type Shape = readonly string[]

function shape(rows: string): Shape {
  const lines = rows.trim().split('\n').map((line) => line.trim())
  if (lines.length !== 16 || lines.some((line) => line.length !== 16)) {
    throw new Error(`Shape must be 16 by 16, got ${lines.length} rows: ${lines[0]}`)
  }
  return lines
}

